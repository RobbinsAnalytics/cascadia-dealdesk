def month_starts(start: date, end: date) -> list:
    """Every month-start between two dates, inclusive of the starting month."""
    out, cur = [], date(start.year, start.month, 1)
    while cur <= end:
        out.append(cur)
        cur = date(cur.year + (cur.month == 12), (cur.month % 12) + 1, 1)
    return out


def add_months(d: date, n: int) -> date:
    """Add n months, clamping the day so 31 Jan + 1 month lands on 28/29 Feb."""
    total = (d.year * 12 + d.month - 1) + n
    y, m = divmod(total, 12)
    m += 1
    last = (date(y + (m == 12), (m % 12) + 1, 1) - timedelta(days=1)).day
    return date(y, m, min(d.day, last))


def nice_round(price: float) -> float:
    """A rep typing a tidy number instead of the exact one. Second-order noise."""
    step = 5 if price < 1_000 else 50 if price < 20_000 else 100
    return float(round(price / step) * step)


def pick_weighted(rng: random.Random, weights: dict):
    """Choose a key from {key: weight}."""
    keys = list(weights)
    return rng.choices(keys, weights=[weights[k] for k in keys], k=1)[0]


