def draw_premium(rng: random.Random, is_renewal: bool) -> float:
    """How much the negotiation actually won over the previous price."""
    hard = rng.random() < PREMIUM_HARD_SHARE
    if is_renewal:
        lo, hi = RENEWAL_PREMIUM_HARD if hard else RENEWAL_PREMIUM_NORMAL
    else:
        lo, hi = PREMIUM_HARD if hard else PREMIUM_NORMAL
    return rng.uniform(lo, hi)


def build_agreements(rng: random.Random, customers: list, products: list) -> list:
    """The governed register: chains, overlaps, scope conflicts, and lapses.

    Four structures are built here on purpose, because each one is a case the
    matching rule has to survive and therefore a case matching_rules.md has to
    document with a worked example:

      chains       — 2-3 agreements over the 24 months, each superseding the last
      overlaps     — a successor back-dated INTO its predecessor's window, which
                     is what forces the supersession test to be time-aware
      family scope — a family-wide agreement that a part-scope agreement
                     overrides for specific parts (the specificity tiebreak)
      lapses       — agreements that run out with no successor, so a naive join
                     on customer + product alone would still pick them up
    """
    by_id = {}
    agreements = []
    seq = [0]

    def new_id():
        seq[0] += 1
        return f"A{seq[0]:04d}"

    def emit(customer, scope, product, family, prior_price, start, end, is_renewal):
        premium = draw_premium(rng, is_renewal)
        agreed = round(prior_price * (1 + premium), 2)
        # Committed capacity, in units, sized to the part's typical order size.
        typical_qty = product["_qty_range"] if product else (5, 40)
        committed = int(rng.randint(*typical_qty) * rng.randint(8, 30))
        row = {
            "agreement_id": new_id(), "customer_id": customer["customer_id"],
            "scope": scope,
            "product_id": product["product_id"] if scope == "part" else None,
            "family": family if scope == "family" else None,
            "agreed_price": agreed,
            "effective_start": start.isoformat(), "effective_end": end.isoformat(),
            "committed_units": committed,
            "approval_ref": f"PA-{start.year}-{seq[0]:04d}",
            "status": None,                     # stamped at the end, as of AS_OF
            "superseded_by": None,
            "prior_price": round(prior_price, 2),
            "premium_pct": round(premium, 4),
        }
        agreements.append(row)
        by_id[row["agreement_id"]] = row
        return row

    def build_chain(customer, scope, product, family, base_price):
        """One customer/scope relationship across the window, as 1-3 links.

        The chain TILES the analysis window: it starts before the window opens
        and normally runs past the far end, with the links being renewals. That
        is how a real book behaves — a customer under agreement stays under
        agreement. Gaps are then introduced deliberately and sparingly, in two
        distinct flavours, because each one is a different business failure:

          mid-chain gap  (SUCCESSOR_GAP_DAYS)   — renewal was late
          tail lapse     (P_CHAIN_LAPSES_AT_END) — renewal never happened

        Both surface as `agreement_lapsed`. Getting this wrong in the other
        direction — chains sitting somewhere inside the window — leaves months
        of trailing "lapsed" coverage behind every agreement and floods the
        no-agreement bucket with noise.
        """
        n_links = pick_weighted(rng, CHAIN_LENGTH_WEIGHTS)
        start = WINDOW_START - timedelta(days=rng.randint(*CHAIN_BACKDATE_DAYS))
        if rng.random() < P_CHAIN_LAPSES_AT_END:
            horizon = WINDOW_END - timedelta(days=rng.randint(*CHAIN_LAPSE_TAIL_DAYS))
        else:
            horizon = WINDOW_END + timedelta(days=rng.randint(*CHAIN_TAIL_DAYS))
        span = (horizon - start).days

        # Interior renewal boundaries, evenly spaced across the span with jitter.
        fracs = sorted(rng.uniform(i / n_links - 0.08, i / n_links + 0.08)
                       for i in range(1, n_links))
        boundaries = [start + timedelta(days=int(span * f)) for f in fracs] + [horizon]

        prior, links, cur_start = base_price, [], start
        for i, boundary in enumerate(boundaries):
            row = emit(customer, scope, product, family, prior, cur_start, boundary, i > 0)
            links.append(row)
            if i == len(boundaries) - 1:
                break
            # Where does the successor start relative to this one's end?
            roll = rng.random()
            if roll < SUCCESSOR_CLEAN_P:
                nxt = boundary + timedelta(days=1)                  # clean handover
            elif roll < SUCCESSOR_CLEAN_P + SUCCESSOR_OVERLAP_P:
                nxt = boundary - timedelta(days=rng.randint(*SUCCESSOR_OVERLAP_DAYS))
            else:
                nxt = boundary + timedelta(days=rng.randint(*SUCCESSOR_GAP_DAYS))
            # A renewal is negotiated up from the price it replaces.
            prior, cur_start = row["agreed_price"], nxt
        # Link the chain: every predecessor points at its successor.
        for a, b in zip(links, links[1:]):
            a["superseded_by"] = b["agreement_id"]
        return links

    products_by_id = {p["product_id"]: p for p in products}
    signing = [c for c in customers if not c["_never_signs"]]
    family_scope_customers = set(
        rng.sample([c["customer_id"] for c in signing],
                   min(N_FAMILY_SCOPE_CUSTOMERS, len(signing))))

    for c in signing:
        basket = [products_by_id[pid] for pid in c["_basket"]]
        fams = sorted({p["family"] for p in basket})

        # --- family-scope agreements -------------------------------------
        family_covered = set()
        if c["customer_id"] in family_scope_customers:
            fam = rng.choice(fams)
            family_covered.add(fam)
            base = FAMILIES[fam]["base_price"] * c["_price_factor"]
            build_chain(c, "family", None, fam, base)

        # --- part-scope agreements ---------------------------------------
        for p in basket:
            # A part already covered by a family agreement only gets its own
            # part-scope agreement some of the time — that is the override case.
            if p["family"] in family_covered:
                if rng.random() > P_PART_OVERRIDE_ON_FAMILY:
                    continue
            elif rng.random() > P_PAIR_COVERED:
                continue          # deliberately uncovered -> never_under_agreement
            # A part that launched after the window opened cannot have been in
            # an agreement signed before it existed.
            if date.fromisoformat(p["launch_date"]) > WINDOW_START:
                continue
            build_chain(c, "part", p, p["family"], p["_list_price"] * c["_price_factor"])

    # --- register-hygiene defects: duplicate registrations, no supersession --
    # Two agreements of equal specificity covering the same part and the same
    # dates, with NOTHING linking them. This is the case the RECENCY tiebreak
    # exists for, and it is a real thing that happens when two people paper the
    # same deal. Effective starts are deliberately different so the tiebreak
    # resolves; an identical start would be an unresolvable tie and would
    # (correctly) fail the run.
    part_agreements = [a for a in agreements if a["scope"] == "part"
                       and a["superseded_by"] is None]
    for src in rng.sample(part_agreements, min(N_UNLINKED_OVERLAPS, len(part_agreements))):
        customer = next(c for c in customers if c["customer_id"] == src["customer_id"])
        product = products_by_id[src["product_id"]]
        start = date.fromisoformat(src["effective_start"]) + timedelta(days=rng.randint(20, 90))
        end = date.fromisoformat(src["effective_end"]) + timedelta(days=rng.randint(5, 60))
        if start >= end:
            continue
        emit(customer, "part", product, product["family"],
             src["prior_price"] * rng.uniform(0.98, 1.03), start, end, True)

    # --- stamp status AS OF the as-of date ---------------------------------
    # This column describes the register TODAY, which is what the agreement
    # timeline on the customer page renders. The MATCHER does not read it: it
    # asks the same two questions as of the QUOTE date instead. Both meanings
    # are spelled out in governance/matching_rules.md.
    for a in agreements:
        successor = by_id.get(a["superseded_by"]) if a["superseded_by"] else None
        if successor and date.fromisoformat(successor["effective_start"]) <= AS_OF:
            a["status"] = "superseded"
        elif date.fromisoformat(a["effective_end"]) < AS_OF:
            a["status"] = "expired"
        else:
            a["status"] = "active"
    return agreements


