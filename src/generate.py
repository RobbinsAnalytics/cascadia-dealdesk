def build_reps(rng: random.Random) -> list:
    """12 reps. Four of them — one especially — will carry most of the leakage.

    Rep discipline is the first of the three concentration drivers. It is what
    makes the "by rep" ranked bar on the exception page have a head and a tail
    instead of twelve equal bars, and it is what turns the finding into a
    coaching conversation rather than a system complaint.
    """
    reps = []
    leaky = set(rng.sample(range(N_REPS), N_LEAKY_REPS))
    standout = rng.choice(sorted(leaky))
    for i, name in enumerate(REP_NAMES):
        if i == standout:
            leak = REP_LEAK_STANDOUT
        elif i in leaky:
            leak = rng.uniform(*REP_LEAK_HIGH)
        else:
            leak = rng.uniform(*REP_LEAK_LOW)
        reps.append({"rep_id": f"R{i + 1:02d}", "name": name,
                     "territory": TERRITORIES[i % len(TERRITORIES)],
                     "_leak_factor": round(leak, 3)})
    return reps


def build_products(rng: random.Random) -> list:
    """120 parts across 6 families, with launch dates and a cost trajectory.

    N_LATE_LAUNCH_PRODUCTS of them launch DURING the analysis window. Those are
    what create genuine `product_launched_after_agreement` coverage gaps: the
    part did not exist when the customer's agreement was negotiated.
    """
    products, per_family = [], N_PRODUCTS // len(FAMILIES)
    late_launch_slots = set(rng.sample(range(N_PRODUCTS), N_LATE_LAUNCH_PRODUCTS))
    idx = 0
    for family, spec in FAMILIES.items():
        for n in range(per_family):
            if idx in late_launch_slots:
                # Launches inside the window -> post-dates existing agreements.
                launch = WINDOW_START + timedelta(days=rng.randint(45, 560))
            else:
                launch = WINDOW_START - timedelta(days=rng.randint(200, 2200))
            list_price = round(spec["base_price"]
                               * rng.uniform(1 - PART_PRICE_SPREAD, 1 + PART_PRICE_SPREAD), 2)
            trend = rng.choices(["down", "flat", "up"], weights=COST_DRIFT_MIX, k=1)[0]
            drift = rng.uniform(*{"down": COST_DRIFT_DOWN, "flat": COST_DRIFT_FLAT,
                                  "up": COST_DRIFT_UP}[trend])
            products.append({
                "product_id": f"P{idx + 1:04d}",
                "part_number": f"{spec['prefix']}-{1000 + (idx * 37) % 8999}",
                "family": family, "launch_date": launch.isoformat(),
                "_list_price": list_price, "_qty_range": spec["qty"],
                "_cost_trend": trend, "_cost_drift": round(drift, 4),
                "_leak_factor": round(rng.uniform(*PRODUCT_LEAK_SPREAD), 3),
            })
            idx += 1
    return products


def build_customers(rng: random.Random, products: list) -> list:
    """40 accounts, each with a basket of parts and a leakage propensity.

    Two groups are planted on purpose and both are declared in the assumptions
    doc, because a reader is entitled to know which findings were designed in:

      * N_HOT_CUSTOMERS  — accounts that carry most of the dollar exposure, so
        the ranked-by-dollars chart has a genuine head.
      * N_MARGIN_EROSION_CUSTOMERS — accounts with near-perfect compliance whose
        parts have RISING standard cost. These produce the second, separate
        finding: the agreement was honoured and the margin still fell.
    """
    up_cost_pool = [p for p in products if p["_cost_trend"] == "up"]
    hot = set(rng.sample(range(N_CUSTOMERS), N_HOT_CUSTOMERS))
    # Erosion accounts are chosen from OUTSIDE the hot set — the whole point is
    # that they look clean on the leakage page.
    erosion = set(rng.sample(sorted(set(range(N_CUSTOMERS)) - hot),
                             N_MARGIN_EROSION_CUSTOMERS))
    exception_accounts = set(rng.sample(sorted(set(range(N_CUSTOMERS)) - erosion),
                                        N_EXCEPTION_ACCOUNTS))
    # Accounts that never signed anything at all — one cause of
    # `never_under_agreement`. Drawn from outside the hot/planted sets so a
    # high-volume account does not single-handedly flood the no-agreement bucket.
    never_sign = set(rng.sample(
        sorted(set(range(N_CUSTOMERS)) - hot - erosion - exception_accounts),
        N_NEVER_SIGN_CUSTOMERS))

    customers = []
    for i, name in enumerate(CUSTOMER_NAMES):
        if i in erosion:
            leak = 0.12                                   # disciplined by design
            basket_pool = up_cost_pool
            basket_size = rng.randint(6, 11)
        elif i in hot:
            leak = rng.uniform(*CUSTOMER_LEAK_HOT)
            basket_pool = products
            basket_size = rng.randint(9, 16)
        else:
            leak = rng.uniform(*CUSTOMER_LEAK_SPREAD)
            basket_pool = products
            basket_size = rng.randint(5, 14)

        # A basket is drawn from 2-3 families so families mean something.
        fams = rng.sample(sorted(FAMILIES), rng.randint(2, 3))
        candidates = [p for p in basket_pool if p["family"] in fams] or basket_pool
        basket = rng.sample(candidates, min(basket_size, len(candidates)))

        customers.append({
            "customer_id": f"C{i + 1:03d}", "name": name,
            "segment": ("Strategic" if i in hot | exception_accounts
                        else rng.choices(SEGMENTS, weights=[0.2, 0.5, 0.3], k=1)[0]),
            "region": rng.choice(REGIONS),
            "_leak_factor": round(leak, 3),
            "_price_factor": round(rng.uniform(0.82, 1.05), 4),   # negotiating power
            "_basket": [p["product_id"] for p in basket],
            "_never_signs": i in never_sign,
            "_is_exception_account": i in exception_accounts,
            "_is_erosion_account": i in erosion,
        })
    return customers


def build_dates() -> list:
    """A plain daily calendar over the analysis window."""
    out, cur = [], WINDOW_START
    while cur <= WINDOW_END:
        out.append({"date_key": int(cur.strftime("%Y%m%d")), "date": cur.isoformat(),
                    "year": cur.year, "quarter": f"Q{(cur.month - 1) // 3 + 1}",
                    "month": cur.month, "month_name": cur.strftime("%B")})
        cur += timedelta(days=1)
    return out


def build_standard_costs(rng: random.Random, products: list) -> list:
    """Quarterly cost steps per part, spanning the whole window with no gaps.

    Cost is NOT decoration. A locked price plus a rising cost is a different
    failure from a rep quoting the wrong number, and the customer page has to
    be able to tell the two apart. The first segment starts before the window
    so every quote date is covered by exactly one segment.
    """
    rows = []
    starts = [date(2024, 1, 1)]
    while starts[-1] < WINDOW_END:
        starts.append(add_months(starts[-1], 3))
    for p in products:
        cost = p["_list_price"] * rng.uniform(*COST_RATIO_AT_START)
        for i, s in enumerate(starts):
            end = (starts[i + 1] - timedelta(days=1)) if i + 1 < len(starts) \
                else date(2099, 12, 31)
            rows.append({"product_id": p["product_id"],
                         "effective_start": s.isoformat(),
                         "effective_end": end.isoformat(),
                         "standard_cost": round(cost, 2)})
            # One quarter of the annual drift, plus a little quarter-to-quarter noise.
            cost *= (1 + p["_cost_drift"] / 4 + rng.gauss(0, 0.004))
    return rows


