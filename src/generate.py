def monthly_line_targets(rng: random.Random) -> dict:
    """Allocate the target line count across 24 months with growth + a Q4 push."""
    months = month_starts(WINDOW_START, WINDOW_END)
    weights = {}
    for m in months:
        w = QUARTER_WEIGHTS[(m.month - 1) // 3 + 1]
        if m >= add_months(WINDOW_START, 12):
            w *= (1 + YOY_GROWTH)
        weights[m] = w
    total_w = sum(weights.values())
    return {m: max(1, round(TARGET_QUOTE_LINES * w / total_w)) for m, w in weights.items()}


def off_agreement_probability(customer, rep, product, agreement, quote_date) -> float:
    """P(this line is quoted off the agreement) — a product of three drivers.

    All three are recoverable from the finished dataset, which is the point:
    the analysis should be able to say WHO, WHEN and WHERE, not just HOW MUCH.

      rep      — discipline varies, and four reps carry the majority
      recency  — probability peaks in the days right after a renegotiation and
                 decays. The stale sheet has not caught up yet.
      account  — a handful of accounts and parts carry most of the exposure
    """
    days_since = (quote_date - date.fromisoformat(agreement["effective_start"])).days
    recency = 1 + RECENCY_PEAK_BOOST * math.exp(-max(days_since, 0) / RECENCY_DECAY_DAYS)
    p = (BASE_OFF_AGREEMENT_RATE * rep["_leak_factor"] * recency
         * customer["_leak_factor"] * product["_leak_factor"])
    return min(max(p, P_OFF_CLAMP[0]), P_OFF_CLAMP[1])


def build_quotes(rng: random.Random, customers: list, products: list,
                 reps: list, agreements: list) -> tuple:
    """Generate quote lines, price them, and convert some of them to bookings."""
    products_by_id = {p["product_id"]: p for p in products}
    agreements_by_customer: dict = {}
    for a in agreements:
        agreements_by_customer.setdefault(a["customer_id"], []).append(a)
    agreement_by_id = {a["agreement_id"]: a for a in agreements}

    # Each account has a primary rep; occasionally someone else covers.
    primary_rep = {c["customer_id"]: reps[i % len(reps)] for i, c in enumerate(customers)}
    # Weight account activity so quote volume itself is concentrated.
    activity = {c["customer_id"]: rng.uniform(0.5, 1.0) * (2.4 if c["_leak_factor"] > 2.5 else 1.0)
                for c in customers}

    lines, bookings = [], []
    quote_seq, booking_seq = [0], [0]
    exception_seq = [0]

    for month, target in monthly_line_targets(rng).items():
        emitted = 0
        while emitted < target:
            customer = rng.choices(customers,
                                   weights=[activity[c["customer_id"]] for c in customers],
                                   k=1)[0]
            if not customer["_basket"]:
                continue
            rep = primary_rep[customer["customer_id"]] if rng.random() < 0.85 \
                else rng.choice(reps)
            last_day = (add_months(month, 1) - timedelta(days=1))
            quote_date = month + timedelta(days=rng.randint(0, (last_day - month).days))
            if not (WINDOW_START <= quote_date <= WINDOW_END):
                continue

            quote_seq[0] += 1
            quote_id = f"Q-{quote_date.year}-{quote_seq[0]:06d}"
            n_lines = min(pick_weighted(rng, LINES_PER_QUOTE_WEIGHTS),
                          len(customer["_basket"]), target - emitted or 1)
            for line_no, pid in enumerate(rng.sample(customer["_basket"], n_lines), start=1):
                product = products_by_id[pid]
                # A part cannot be quoted before it launches.
                if date.fromisoformat(product["launch_date"]) > quote_date:
                    continue
                line = price_line(rng, customer, product, rep, quote_date, quote_id,
                                  line_no, agreements_by_customer.get(customer["customer_id"], []),
                                  agreement_by_id, exception_seq)
                lines.append(line)
                emitted += 1
                book = maybe_book(rng, line, customer, booking_seq)
                if book:
                    bookings.append(book)
    return lines, bookings


def price_line(rng, customer, product, rep, quote_date, quote_id, line_no,
               customer_agreements, agreement_by_id, exception_seq) -> dict:
    """Decide what number the rep typed. This is where the mechanism lives."""
    winner, _ = resolve_agreement(customer_agreements, product["product_id"],
                                  product["family"], quote_date, agreement_by_id)
    qty = rng.randint(*product["_qty_range"])
    approval_ref = reason_code = None

    if winner is None:
        # No agreement governs, so there is no premium to lose and no variance
        # to measure. The line is priced at the going rate for that account.
        price = product["_list_price"] * customer["_price_factor"] * (1 + rng.gauss(0, 0.02))
        stage = None
    else:
        agreed, prior = winner["agreed_price"], winner["prior_price"]
        p_exception = (EXCEPTION_BASE_RATE
                       * (EXCEPTION_ACCOUNT_BOOST if customer["_is_exception_account"]
                          else EXCEPTION_OTHER_DAMPEN))
        if rng.random() < p_exception:
            # A DOCUMENTED, APPROVED deviation. These are the legitimate
            # exceptions that make threshold calibration a real exercise
            # instead of theatre — and some of them are priced ABOVE the
            # agreement, because "exception" does not mean "loss".
            magnitude = rng.uniform(*EXCEPTION_MAGNITUDE)
            sign = 1 if rng.random() < P_EXCEPTION_POSITIVE else -1
            price = agreed * (1 + sign * magnitude)
            exception_seq[0] += 1
            approval_ref = f"DR-{quote_date.year}-{exception_seq[0]:04d}"
            reason_code = rng.choice(EXCEPTION_REASON_CODES)
        elif rng.random() < off_agreement_probability(customer, rep, product,
                                                      winner, quote_date):
            # THE MECHANISM: the rep quotes the PRIOR price. Not a random
            # perturbation of the agreed price — the previous number, pulled
            # from habit or from a spreadsheet that has not caught up.
            price = prior * (1 + rng.gauss(0, OFF_AGREEMENT_JITTER))
            if rng.random() < ROUND_TO_NICE_NUMBER_P:
                price = nice_round(price)
        else:
            # Priced to the agreement, give or take rounding.
            price = agreed * (1 + rng.uniform(-ON_AGREEMENT_JITTER, ON_AGREEMENT_JITTER))
        stage = None

    price = round(price, 2)
    # Safety rail: a line INTENDED as on-agreement must land inside the
    # tolerance band after rounding, and an intended deviation must land
    # outside it. Without this a nice-round could accidentally flip a line's
    # match_status and quietly corrupt the target mix.
    if winner is not None:
        agreed = winner["agreed_price"]
        intended_on = abs(price - agreed) <= TOLERANCE_PCT * agreed
        actually_on = abs(round(price, 2) - agreed) <= TOLERANCE_PCT * agreed
        if intended_on != actually_on:                      # pragma: no cover
            price = round(agreed * (1 + rng.uniform(-ON_AGREEMENT_JITTER,
                                                    ON_AGREEMENT_JITTER)), 2)

    return {"quote_id": quote_id, "line_no": line_no,
            "customer_id": customer["customer_id"], "product_id": product["product_id"],
            "rep_id": rep["rep_id"], "quote_date": quote_date.isoformat(),
            "quantity": qty, "quoted_price": price, "stage": stage,
            "approval_ref": approval_ref, "exception_reason_code": reason_code}


def maybe_book(rng, line, customer, booking_seq):
    """Convert a quote line to a booking, or leave it open or lost.

    Bookings are load-bearing here, not staged and forgotten. They are what
    split exposure into money already invoiced and money still in the funnel —
    which is the deal-desk argument stated in dollars.

    Every line gets an eventual outcome AND a date on which that outcome lands.
    If the decision date falls beyond the end of the window, the line is still
    OPEN as at the as-of date, whichever way it was going to go. Modelling it
    this way rather than "recent lines are probably open" is what makes open
    exposure a real, dated funnel rather than a fudge factor.
    """
    quote_date = date.fromisoformat(line["quote_date"])
    p_convert = CONVERSION_BY_SEGMENT[customer["segment"]]
    roll = rng.random()

    if roll < p_convert:
        lag = timedelta(days=int(rng.triangular(BOOKING_LAG_DAYS[0],
                                                BOOKING_LAG_DAYS[1],
                                                BOOKING_LAG_DAYS[0] + 15)))
        booking_date = quote_date + lag
        if booking_date > WINDOW_END:
            line["stage"] = "open"          # would have booked, hasn't yet
            return None
        line["stage"] = "won"
        booking_seq[0] += 1
        price = line["quoted_price"]
        if rng.random() < P_BOOKED_PRICE_DIFFERS:
            # The price moved between quote and order. Model it; never assume
            # booked_price == quoted_price.
            price = round(price * (1 + rng.gauss(0, BOOKED_PRICE_DRIFT)), 2)
        qty = line["quantity"]
        if rng.random() < P_PARTIAL_QUANTITY:
            qty = max(1, int(qty * rng.uniform(*PARTIAL_QUANTITY_RANGE)))
        return {"booking_id": f"BK-{booking_seq[0]:06d}", "quote_id": line["quote_id"],
                "line_no": line["line_no"], "customer_id": line["customer_id"],
                "product_id": line["product_id"],
                "booking_date": booking_date.isoformat(),
                "booked_quantity": qty, "booked_price": price}

    # Didn't convert — but a loss takes time to become a loss. If the customer
    # has not walked away yet as at the window end, the line is still open.
    decided_on = quote_date + timedelta(days=rng.randint(*LOSS_DECISION_LAG_DAYS))
    line["stage"] = "lost" if decided_on <= WINDOW_END else "open"
    return None


