"""
generate.py — Seeded synthetic generator for Cascadia Deal Desk.

Cascadia Deal Desk · Part A

    ALL DATA IN THIS PROJECT IS SYNTHETIC. It is generated by this file from a
    fixed seed. There is no real company, customer, part number, price, or
    person anywhere in it, and there never will be. Every figure the site
    displays traces back to the parameter block below.

Output: data/raw/dim_customer.csv        data/raw/fact_quote_line.csv
        data/raw/dim_product.csv         data/raw/fact_booking.csv
        data/raw/dim_rep.csv             data/raw/fact_standard_cost.csv
        data/raw/dim_date.csv            data/raw/generator_manifest.json
        data/raw/dim_agreement.csv       governance/generator_assumptions.md

WHY THIS FILE IS SHAPED THE WAY IT IS
-------------------------------------
The easy way to build a pricing dataset is to draw the quoted price from a
distribution centred on the agreed price. That produces a cloud of small,
directionless variances — an exception table with no story in it, and a
threshold control that does nothing interesting when you drag it.

So variance here is not drawn. It is GENERATED FROM A MECHANISM:

    Every customer/product relationship carries a prior_price — what that
    customer paid before the current agreement. When an agreement is signed,
    the agreed_price sits at a PREMIUM above prior_price. An off-agreement
    line is a rep quoting the PRIOR price: the old number, pulled from habit
    or from a stale spreadsheet.

That single mechanism gives the analysis every property it needs for free.
The variance is negative, because the premium was positive. It is larger
where the premium was larger, because it IS the premium. And it is
explainable, because the counterfactual is a real number sitting in the data.

Jitter exists on top of that (a rounded number, a slightly stale sheet), but
it is deliberately second-order. It is never the driver.

Usage:
    python src/generate.py
"""

