def main(out_dir: Path = RAW_DIR, quiet: bool = False) -> None:
    """Generate the whole dataset.

    `out_dir` is overridable so validate.py can regenerate into a temporary
    folder and prove the seed really is reproducible, without touching the
    committed artifact in data/raw/.
    """
    rng = random.Random(SEED)
    out_dir.mkdir(parents=True, exist_ok=True)
    ASSUMPTIONS_PATH.parent.mkdir(parents=True, exist_ok=True)

    reps = build_reps(rng)
    products = build_products(rng)
    customers = build_customers(rng, products)
    dates = build_dates()
    costs = build_standard_costs(rng, products)
    agreements = build_agreements(rng, customers, products)
    lines, bookings = build_quotes(rng, customers, products, reps, agreements)

    # --- realized mix, measured with the SAME matcher conform.py will use ---
    agreements_by_customer: dict = {}
    for a in agreements:
        agreements_by_customer.setdefault(a["customer_id"], []).append(a)
    agreement_by_id = {a["agreement_id"]: a for a in agreements}
    products_by_id = {p["product_id"]: p for p in products}

    from conform import no_agreement_reason
    tally = {"priced_to_agreement": 0, "priced_off_agreement": 0,
             "no_governing_agreement": 0}
    reasons: dict = {}
    for ln in lines:
        product = products_by_id[ln["product_id"]]
        qd = date.fromisoformat(ln["quote_date"])
        cust_ags = agreements_by_customer.get(ln["customer_id"], [])
        winner, _ = resolve_agreement(cust_ags, ln["product_id"], product["family"],
                                      qd, agreement_by_id)
        if winner is None:
            tally["no_governing_agreement"] += 1
            cause = no_agreement_reason(cust_ags, ln["product_id"], product["family"],
                                        qd, date.fromisoformat(product["launch_date"]))
            reasons[cause] = reasons.get(cause, 0) + 1
        elif abs(ln["quoted_price"] - winner["agreed_price"]) <= TOLERANCE_PCT * winner["agreed_price"]:
            tally["priced_to_agreement"] += 1
        else:
            tally["priced_off_agreement"] += 1

    realized = dict(tally)
    realized["total_lines"] = len(lines)
    realized["covered_lines"] = tally["priced_to_agreement"] + tally["priced_off_agreement"]
    realized["approved_exceptions"] = sum(1 for ln in lines if ln["approval_ref"])
    realized["no_agreement_reasons"] = reasons

    # --- write the raw layer ------------------------------------------------
    def public(rows, cols):
        """Drop the generator's private '_' columns; those are scaffolding."""
        return pd.DataFrame(rows)[cols]

    frames = {
        "dim_customer": public(customers, ["customer_id", "name", "segment", "region"]),
        "dim_product": public(products, ["product_id", "part_number", "family", "launch_date"]),
        "dim_rep": public(reps, ["rep_id", "name", "territory"]),
        "dim_date": pd.DataFrame(dates),
        "dim_agreement": public(agreements, [
            "agreement_id", "customer_id", "scope", "product_id", "family",
            "agreed_price", "effective_start", "effective_end", "committed_units",
            "approval_ref", "status", "superseded_by", "prior_price", "premium_pct"]),
        "fact_quote_line": public(lines, [
            "quote_id", "line_no", "customer_id", "product_id", "rep_id",
            "quote_date", "quantity", "quoted_price", "stage", "approval_ref",
            "exception_reason_code"]),
        "fact_booking": public(bookings, [
            "booking_id", "quote_id", "line_no", "customer_id", "product_id",
            "booking_date", "booked_quantity", "booked_price"]),
        "fact_standard_cost": pd.DataFrame(costs),
    }
    for name, df in frames.items():
        df.to_csv(out_dir / f"{name}.csv", index=False, lineterminator="\n")

    manifest = {
        "generator": "src/generate.py", "seed": SEED,
        "as_of": AS_OF.isoformat(),
        "window": {"start": WINDOW_START.isoformat(), "end": WINDOW_END.isoformat()},
        "disclosure": DISCLOSURE,
        "tolerance_pct": TOLERANCE_PCT,
        "row_counts": {n: int(len(df)) for n, df in frames.items()},
        "realized_mix": {k: v for k, v in realized.items() if k != "no_agreement_reasons"},
        "no_agreement_reasons": reasons,
    }
    (out_dir / "generator_manifest.json").write_text(json.dumps(manifest, indent=2),
                                                     encoding="utf-8")
    if quiet:                       # regeneration-for-verification run; leave the
        return                      # committed governance doc alone
    write_assumptions(realized)

    print(f"Wrote {len(frames)} CSVs to {out_dir}")
    for name, df in frames.items():
        print(f"  {name}: {len(df):,} rows")
    t = realized["total_lines"]
    print("Realized mix:")
    for k in ("priced_to_agreement", "priced_off_agreement", "no_governing_agreement"):
        print(f"  {k}: {realized[k]:,} ({100 * realized[k] / t:.1f}%)")
    print(f"  priced_to_agreement as share of COVERED lines: "
          f"{100 * realized['priced_to_agreement'] / realized['covered_lines']:.1f}%")
    print(f"  approved exceptions: {realized['approved_exceptions']:,} "
          f"({100 * realized['approved_exceptions'] / max(realized['priced_off_agreement'], 1):.1f}% "
          f"of off-agreement)")
    print(f"  no-agreement causes: {reasons}")
    print(f"Wrote {ASSUMPTIONS_PATH}")


